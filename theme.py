def _ecg_path(reps: int = 2) -> str:
    d = "M0 50"
    for r in range(reps):
        o = 400 * r
        d += (f" H{o+90} L{o+100} 46 L{o+110} 50 H{o+150} L{o+160} 58 L{o+172} 10"
              f" L{o+184} 90 L{o+196} 50 H{o+235} Q{o+262} 24 {o+290} 50 H{o+400}")
    return d


def _dna_svg() -> str:
    parts = []
    dur = '<animate attributeName="{}" values="{}" dur="4s" repeatCount="indefinite"/>'
    for i in range(11):
        y, ph = 28 + i * 24, i * 0.6
        a = [2 * math.pi * k / 12 + ph for k in range(13)]
        x1 = ";".join(f"{50 + 34 * math.cos(t):.1f}" for t in a)
        x2 = ";".join(f"{50 - 34 * math.cos(t):.1f}" for t in a)
        r1 = ";".join(f"{3.6 + 1.5 * math.sin(t):.2f}" for t in a)
        r2 = ";".join(f"{3.6 - 1.5 * math.sin(t):.2f}" for t in a)
        parts.append(
            f'<line y1="{y}" y2="{y}" stroke="rgba(94,234,212,.35)" stroke-width="1.2">'
            + dur.format("x1", x1) + dur.format("x2", x2) + "</line>"
            f'<circle cy="{y}" fill="#5EEAD4">' + dur.format("cx", x1) + dur.format("r", r1) + "</circle>"
            f'<circle cy="{y}" fill="#60A5FA">' + dur.format("cx", x2) + dur.format("r", r2) + "</circle>"
        )
    return '<svg viewBox="0 0 100 290" preserveAspectRatio="xMidYMid meet">' + "".join(parts) + "</svg>"


