def chips_html(items, hits=None) -> str:
    hits = hits or set()
    out = "".join(
        f'<span class="{"chip hit" if s in hits else "chip"}" style="--cd:{min(i, 30) * .035:.2f}s">{_lab(s)}</span>'
        for i, s in enumerate(items))
    return f'<div class="chips">{out}</div>'


