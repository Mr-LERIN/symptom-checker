def _ring(size, sw, pct, label_size, delay, gradient=False):
    r = (size - sw) / 2
    c = 2 * math.pi * r
    off = c * (1 - max(0, min(1, pct)))
    stroke = "url(#gg)" if gradient else "#5EEAD4"
    defs = ('<defs><linearGradient id="gg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#60A5FA"/>'
            '<stop offset="1" stop-color="#5EEAD4"/></linearGradient></defs>') if gradient else ""
    return (f'<div class="gauge" style="--s:{size}px;--c:{c:.1f};--o:{off:.1f};--d:{delay}">'
            f'<svg width="{size}" height="{size}" viewBox="0 0 {size} {size}">{defs}'
            f'<circle class="track" cx="{size/2}" cy="{size/2}" r="{r}" stroke-width="{sw}"/>'
            f'<circle class="arc" cx="{size/2}" cy="{size/2}" r="{r}" stroke-width="{sw}" stroke="{stroke}"/></svg>'
            f'<div class="val" style="font-size:{label_size}px"><span>{pct*100:.0f}<small>%</small></span></div></div>')


def results(items, matched):
    """items: list of dicts {disease, confidence, overlap, profile}. Values 0-1."""
    matched = set(matched)
    top = items[0]
    summary = (
        '<div class="sum">'
        f'<div class="cell" style="--d:0s"><span class="mono">Symptoms matched</span><div class="big">{len(matched)}</div></div>'
        f'<div class="cell" style="--d:.08s"><span class="mono">Top candidate</span><div class="big">{_h.escape(top["disease"])}</div></div>'
        f'<div class="cell" style="--d:.16s"><span class="mono">Confidence</span><div class="big">{top["confidence"]*100:.0f}%</div></div>'
        '</div>'
    )
    cards = []
    for rank, it in enumerate(items, 1):
        delay = f"{0.14 * (rank - 1) + .2:.2f}s"
        conf, ov = max(0, min(1, it["confidence"])), max(0, min(1, it["overlap"]))
        prof = sorted(it["profile"], key=lambda s: (s not in matched, s))
        chips = chips_html(prof, matched) if prof else '<div class="mono">No profile available</div>'
        bars = (f'<div class="lbl mono"><span>Symptom overlap</span><span>{ov*100:.0f}%</span></div>'
                f'<div class="bar" style="--w:{ov*100:.1f}%"><span></span></div>')
        if rank == 1:
            cards.append(
                f'<div class="rcard first" style="--d:{delay}">{_ring(150, 9, conf, 40, delay, True)}'
                f'<div><span class="mono">Most likely · 01</span><div class="nm">{_h.escape(it["disease"])}</div>'
                f'{bars}<div class="lbl mono"><span>Typical symptoms</span></div>{chips}</div></div>')
        else:
            cards.append(
                f'<div class="rcard" style="--d:{delay}"><div class="rtop"><div><span class="mono">Match · 0{rank}</span>'
                f'<div class="nm">{_h.escape(it["disease"])}</div></div>{_ring(58, 5, conf, 15, delay)}</div>'
                f'{bars}<div class="lbl mono"><span>Typical symptoms</span></div>{chips}</div>')
    _md(summary + '<div class="rgrid">' + "".join(cards) + "</div>")


